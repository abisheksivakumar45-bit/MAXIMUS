import { useCallback, useState } from 'react';
import { Link, useParams } from 'react-router-dom';

import { Alert } from '../../components/ui/Alert';
import { Button } from '../../components/ui/Button';
import { Card, CardHeader } from '../../components/ui/Card';
import { EmptyState } from '../../components/ui/EmptyState';
import { ErrorState } from '../../components/ui/ErrorState';
import { LoadingState } from '../../components/ui/LoadingState';
import { PageHeader } from '../../components/ui/PageHeader';
import { StatusPill } from '../../components/ui/StatusPill';
import { useApiResource } from '../../hooks/useApiResource';
import { ApiError, api } from '../../lib/api';
import type { Roadmap } from '../../types/roadmap';
import {
  ITEM_STATUS_LABELS,
  RESOURCE_TYPE_LABELS,
  ROADMAP_STATUS_LABELS,
  ROADMAP_STATUS_TONES,
  formatDate,
  formatDuration,
} from './roadmapMeta';

/**
 * Roadmap detail (master-spec §4).
 *
 * Everything rendered here is persisted, validated backend data. Milestone and
 * task statuses are read-only in Phase 4: progress tracking belongs to Phase 5,
 * so no checkbox pretends to save anything.
 */
export function RoadmapDetailPage() {
  const { roadmapId } = useParams<{ roadmapId: string }>();
  const loadRoadmap = useCallback(() => {
    if (!roadmapId) {
      return Promise.reject(new ApiError(404, 'Roadmap not found.'));
    }
    return api.roadmaps.get(roadmapId);
  }, [roadmapId]);
  const roadmapState = useApiResource<Roadmap>(loadRoadmap);

  const [approving, setApproving] = useState(false);
  const [approvalError, setApprovalError] = useState<string | null>(null);

  async function approve() {
    if (approving || !roadmapState.data) {
      return;
    }
    setApproving(true);
    setApprovalError(null);
    try {
      await api.roadmaps.approve(roadmapState.data.id);
      roadmapState.reload();
    } catch (error) {
      setApprovalError(
        error instanceof ApiError ? error.message : 'An unexpected error occurred.',
      );
    } finally {
      setApproving(false);
    }
  }

  if (roadmapState.status === 'loading') {
    return (
      <div className="flex flex-col gap-6">
        <PageHeader title="Roadmap" description="Loading the saved plan…" />
        <Card>
          <LoadingState />
        </Card>
      </div>
    );
  }

  if (roadmapState.status === 'error') {
    return (
      <div className="flex flex-col gap-6">
        <PageHeader title="Roadmap" />
        <Card>
          <ErrorState message={roadmapState.error.message} onRetry={roadmapState.reload} />
          <p className="mt-4 text-sm">
            <Link to="/roadmaps" className="text-accent underline">
              Back to roadmaps
            </Link>
          </p>
        </Card>
      </div>
    );
  }

  const roadmap = roadmapState.data;
  const taskCount = roadmap.milestones.reduce(
    (total, milestone) => total + milestone.tasks.length,
    0,
  );

  return (
    <div className="flex flex-col gap-6">
      <PageHeader
        title={roadmap.title}
        description={`Plan for ${roadmap.goal_name} · ${roadmap.goal_category_label}`}
        action={
          <div className="flex flex-wrap items-center gap-2">
            <Link to="/roadmaps" className="text-muted hover:text-ink text-sm underline">
              Back to roadmaps
            </Link>
            {roadmap.status !== 'active' ? (
              <Button onClick={() => void approve()} loading={approving}>
                Approve plan
              </Button>
            ) : null}
          </div>
        }
      />

      {approvalError ? <Alert tone="danger">{approvalError}</Alert> : null}

      <Card>
        <div className="flex flex-wrap items-start justify-between gap-4">
          <div>
            <div className="flex flex-wrap items-center gap-2">
              <StatusPill
                tone={ROADMAP_STATUS_TONES[roadmap.status]}
                label={ROADMAP_STATUS_LABELS[roadmap.status]}
              />
              <span className="text-faint text-xs">
                Generated by {roadmap.provider} · {roadmap.model}
              </span>
            </div>
            <p className="text-ink mt-3 max-w-prose text-sm">{roadmap.description}</p>
          </div>
        </div>

        <dl className="mt-5 grid gap-x-6 gap-y-4 border-t border-line pt-5 text-sm sm:grid-cols-2 lg:grid-cols-4">
          <div>
            <dt className="text-faint text-xs uppercase">Goal</dt>
            <dd className="text-ink mt-0.5">{roadmap.goal_name}</dd>
          </div>
          <div>
            <dt className="text-faint text-xs uppercase">Duration</dt>
            <dd className="text-ink mt-0.5">
              {formatDuration(roadmap.estimated_duration_weeks)}
            </dd>
          </div>
          <div>
            <dt className="text-faint text-xs uppercase">Level</dt>
            <dd className="text-ink mt-0.5">
              {roadmap.starting_level} → {roadmap.target_level}
            </dd>
          </div>
          <div>
            <dt className="text-faint text-xs uppercase">Plan</dt>
            <dd className="text-ink mt-0.5">
              {roadmap.milestones.length}{' '}
              {roadmap.milestones.length === 1 ? 'milestone' : 'milestones'} · {taskCount}{' '}
              {taskCount === 1 ? 'task' : 'tasks'}
            </dd>
          </div>
        </dl>

        <div className="border-line mt-5 border-t pt-5">
          <h2 className="text-ink text-sm font-semibold">Objective</h2>
          <p className="text-muted mt-1 max-w-prose text-sm">{roadmap.objective}</p>
          <p className="text-faint mt-2 text-xs">
            Saved {formatDate(roadmap.created_at)}
            {roadmap.approved_at ? ` · approved ${formatDate(roadmap.approved_at)}` : ''}
          </p>
        </div>

        {roadmap.status === 'draft' ? (
          <div className="mt-4">
            <Alert tone="info">
              This is a draft. Approving it makes it the active plan for this goal. Nothing is
              marked complete until you track progress in a later phase.
            </Alert>
          </div>
        ) : null}
        {roadmap.status === 'archived' ? (
          <div className="mt-4">
            <Alert tone="info">
              This plan is archived because a newer plan for the same goal was approved. It is
              kept for reference.
            </Alert>
          </div>
        ) : null}
      </Card>

      <section aria-labelledby="milestones-heading" className="flex flex-col gap-4">
        <h2 id="milestones-heading" className="text-lg font-semibold tracking-tight">
          Milestones
        </h2>

        {roadmap.milestones.length === 0 ? (
          <EmptyState
            title="No milestones"
            description="This roadmap has no stored milestones. That should not happen; please regenerate it."
          />
        ) : (
          <ol className="flex flex-col gap-4">
            {roadmap.milestones.map((milestone) => (
              <li key={milestone.id}>
                <Card as="article">
                  <CardHeader
                    title={`${milestone.position + 1}. ${milestone.title}`}
                    description={`${formatDuration(milestone.estimated_duration_weeks)} · ${ITEM_STATUS_LABELS[milestone.status]}`}
                  />
                  <p className="text-muted max-w-prose text-sm">{milestone.description}</p>
                  <p className="text-ink mt-3 text-sm">
                    <span className="text-faint text-xs uppercase">Completion criteria: </span>
                    {milestone.completion_criteria}
                  </p>

                  <div className="border-line mt-4 border-t pt-4">
                    <h3 className="text-ink text-sm font-semibold">
                      Tasks ({milestone.tasks.length})
                    </h3>
                    {milestone.tasks.length === 0 ? (
                      <p className="text-muted mt-1 text-sm">No tasks stored for this milestone.</p>
                    ) : (
                      <ul className="mt-3 flex flex-col gap-3">
                        {milestone.tasks.map((task) => (
                          <li
                            key={task.id}
                            className="bg-surface-raised/40 rounded-control border border-line px-3 py-3"
                          >
                            <div className="flex flex-wrap items-start justify-between gap-2">
                              <p className="text-ink text-sm font-medium">{task.title}</p>
                              <span className="text-faint text-xs">
                                {ITEM_STATUS_LABELS[task.status]}
                                {task.estimated_minutes
                                  ? ` · ~${task.estimated_minutes} min`
                                  : ''}
                              </span>
                            </div>
                            <p className="text-muted mt-1 text-sm">{task.description}</p>
                            {task.completion_criteria ? (
                              <p className="text-faint mt-2 text-xs">
                                Done when: {task.completion_criteria}
                              </p>
                            ) : null}
                          </li>
                        ))}
                      </ul>
                    )}
                  </div>

                  {milestone.resources.length > 0 ? (
                    <div className="border-line mt-4 border-t pt-4">
                      <h3 className="text-ink text-sm font-semibold">Resources</h3>
                      <ul className="mt-2 flex flex-col gap-2">
                        {milestone.resources.map((resource) => (
                          <li key={resource.id} className="text-sm">
                            {resource.url ? (
                              <a
                                href={resource.url}
                                target="_blank"
                                rel="noopener noreferrer"
                                className="text-accent underline"
                              >
                                {resource.title}
                              </a>
                            ) : (
                              <span className="text-ink">{resource.title}</span>
                            )}
                            <span className="text-faint text-xs">
                              {' '}
                              · {RESOURCE_TYPE_LABELS[resource.resource_type] ?? 'Resource'}
                            </span>
                            {resource.note ? (
                              <p className="text-muted mt-0.5 text-xs">{resource.note}</p>
                            ) : null}
                          </li>
                        ))}
                      </ul>
                    </div>
                  ) : null}
                </Card>
              </li>
            ))}
          </ol>
        )}
      </section>
    </div>
  );
}
